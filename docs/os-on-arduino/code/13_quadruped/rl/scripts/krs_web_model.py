"""Write the KRS robot's MJCF for the browser walking simulation.

The browser page (docs/assembly/quadruped/walk/) runs MuJoCo WASM on a plain
MJCF. For the KRS robot that MJCF is taken from mjlab itself -- the entity the
KrsQuad-* tasks build, after CollisionCfg and the actuator cfg are applied --
so the actuators (kp, kd, force limit), joint damping/friction/armature and the
contact geoms are exactly the nominal training ones rather than restated by
hand. On top of it this adds what the training scene adds: the solver options,
a ground plane and the home keyframe. The 4-8 physics-step command delay is
applied in walk_core.js, as for the Feetech robot.

The converter writes one STL per mesh instance (196 files, 30 distinct); the
browser fetches each file separately, so identical files are merged.

Run inside the upstream checkout (it imports ``src.tasks``)::

    source rl/scripts/env.sh
    cd "$ARDUINO_QUAD_UPSTREAM"
    python "$ARDUINO_QUAD_ROOT/rl/scripts/krs_web_model.py" \
        "$ARDUINO_QUAD_ROOT/../docs/assembly/quadruped/walk/model"
"""
import argparse
import hashlib
import os
import shutil
import xml.etree.ElementTree as ET

PREFIX = "krs_"  # keeps the KRS meshes apart from the Feetech ones in assets/


def main() -> int:
  ap = argparse.ArgumentParser(description=__doc__,
                               formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("outdir", help="the walk page's model/ directory")
  args = ap.parse_args()

  import mujoco

  import src.tasks  # noqa: F401
  from mjlab.entity.entity import Entity
  from mjlab.tasks.registry import load_env_cfg

  from src.tasks.velocity.config.arduino_quad import krs_robot_cfg as R

  env_cfg = load_env_cfg("KrsQuad-Walk", play=True)
  sim = env_cfg.sim.mujoco
  spec = Entity(R.get_krs_quad_robot_cfg()).spec

  spec.option.timestep = sim.timestep
  spec.option.integrator = mujoco.mjtIntegrator.mjINT_IMPLICITFAST
  assert sim.integrator == "implicitfast", sim.integrator
  spec.option.iterations = sim.iterations
  spec.option.ls_iterations = sim.ls_iterations
  spec.option.ccd_iterations = sim.ccd_iterations
  ground = spec.worldbody.add_geom()
  ground.name = "ground"
  ground.type = mujoco.mjtGeom.mjGEOM_PLANE
  ground.size = [5, 5, 0.1]
  ground.contype = 1
  ground.conaffinity = 1
  ground.rgba = [0.8, 0.8, 0.8, 1]

  joints = [j.name for j in spec.joints if j.type == mujoco.mjtJoint.mjJNT_HINGE]
  key = spec.add_key()
  key.name = "home"
  key.qpos = [0.0, 0.0, R.HOME_BASE_HEIGHT, 1.0, 0.0, 0.0, 0.0] + [
    R.HOME_JOINT_POS[j] for j in joints]
  key.ctrl = [R.HOME_JOINT_POS[a.target] for a in spec.actuators]

  root = ET.fromstring(spec.to_xml())
  root.set("model", "krs_quad_robot")
  src_dir = os.path.join(os.path.dirname(str(R.KRS_QUAD_XML)), "assets")
  out_assets = os.path.join(args.outdir, "assets")
  os.makedirs(out_assets, exist_ok=True)
  for old in os.listdir(out_assets):
    if old.startswith(PREFIX):
      os.remove(os.path.join(out_assets, old))
  by_hash = {}
  n_mesh = 0
  for mesh in root.iter("mesh"):
    fn = mesh.get("file")
    if fn is None:
      continue
    n_mesh += 1
    path = os.path.join(src_dir, os.path.basename(fn))
    digest = hashlib.sha1(open(path, "rb").read()).hexdigest()
    if digest not in by_hash:
      # Several parts share a stem (a servo case is split by colour), so the
      # n-th distinct file of a stem gets a number.
      stem = os.path.basename(fn).rsplit("_", 1)[0]
      taken = set(by_hash.values())
      name, k = "{}{}.stl".format(PREFIX, stem), 1
      while name in taken:
        k += 1
        name = "{}{}_{}.stl".format(PREFIX, stem, k)
      by_hash[digest] = name
      shutil.copyfile(path, os.path.join(out_assets, by_hash[digest]))
    mesh.set("file", by_hash[digest])
  assert len(set(by_hash.values())) == len(by_hash), "mesh name collision"

  comment = ET.Comment(
    " GENERATED by rl/scripts/krs_web_model.py from the KrsQuad-Walk entity "
    "(krs_quad_robot/mjcf/krs_quad_robot.xml + rl/krs_robot_cfg.py). "
    "Nominal training physics; the command delay is applied by walk_core.js. ")
  root.insert(0, comment)
  ET.indent(root, space="  ")
  out = os.path.join(args.outdir, "krs_quad_robot.xml")
  with open(out, "w") as f:
    f.write(ET.tostring(root, encoding="unicode"))
    f.write("\n")

  # Compile what was written, from disk, the way the browser will.
  model = mujoco.MjModel.from_xml_path(out)
  data = mujoco.MjData(model)
  mujoco.mj_resetDataKeyframe(model, data, model.key("home").id)
  for _ in range(400):
    mujoco.mj_step(model, data)
  print("wrote {} ({} meshes -> {} files), mass {:.1f} g, nu {}; after 2 s at home "
        "the base is at {:.4f} m".format(out, n_mesh, len(by_hash),
                                         model.body_subtreemass[0] * 1e3, model.nu,
                                         data.qpos[2]))
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
