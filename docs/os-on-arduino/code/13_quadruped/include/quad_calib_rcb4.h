// RCB-4 mini 版のサーボ構成 (env:uno_r4_wifi_rcb4 だけが使う)。
//
// サーボの ID は Feetech 版と同じ振り方で、quad_calib.h の QUAD_SERVO_ID を
// そのまま使う。RCB-4 のサーボ番号は、右の SIO ポートに挿すと ID * 2、左だと
// ID * 2 + 1 になる。どちらに挿したかは起動時に両方を読んで見つける。
//
// 下の 2 つは quad_calib.h と同じく、ポリシーの 8 出力の順に並んでいる。
// **並べ替えてはいけない。**
//   FL_hip, FL_knee, RL_hip, RL_knee, RR_hip, RR_knee, FR_hip, FR_knee
//
// 機体ごとに違う値で、推測で埋めてはいけない。間違った向きやゼロ点のまま
// 立ち上げると、起動直後の home への移動で脚が暴れる。埋め終わるまでは
// QUAD_RCB4_CALIBRATED を 0 のままにしておくこと。0 の間は読むだけで、
// 目標角は送らない (脱力は送る。起動時の割り当てと free コマンド)。
//
// 測り方: 機体を吊るし、4 本とも脚をまっすぐ真下に伸ばした姿勢 (CAD の 0 度)
// にして raw を打つ。出たパルスを ZERO に書く。次に脚を 1 本ずつ前へ振って
// raw を打ち、rad の符号が URDF の向き (正で足が後ろへ) と逆なら SIGN を -1 にする。
#pragma once

#define QUAD_RCB4_CALIBRATED 1

// URDF の関節が回る向きにサーボが回るかどうか。+1 か -1。本書の実機では
// 股も膝も、足先を後ろへ振るとパルスが左の脚で減り、右の脚で増えた
// (Feetech 版の QUAD_SERVO_SIGN と同じ並び)。
static const float QUAD_RCB4_SIGN[8] = {
    -1.0f, -1.0f, -1.0f, -1.0f, 1.0f, 1.0f, 1.0f, 1.0f};

// 関節角 0 rad (脚がまっすぐ) のときのパルス。ICS の中央は 7500、
// 1 度あたり 4000/135 = 29.63 パルス。下は本書の実機で、脱力して 4 本とも
// まっすぐ真下に伸ばし、raw を 3 回読んだ平均。
static const float QUAD_RCB4_ZERO[8] = {
    7476.0f, 7519.0f, 7433.0f, 7403.0f, 7679.0f, 7785.0f, 7419.0f, 7206.0f};
